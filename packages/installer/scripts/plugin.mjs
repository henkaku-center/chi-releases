import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { resolve, relative } from 'node:path';
import { sources } from '../src/pins.ts';

// This same closure is exported as original blobs, scanned, and built in the
// public release repository. No private checkout or compiler is needed on a host.
export async function buildPlugin() {
  const root = fileURLToPath(new URL('../../../', import.meta.url));
  for (const [path, hash] of Object.entries(sources.chi.files)) {
    if (createHash('sha256').update(await readFile(resolve(root, path))).digest('hex') !== hash) throw new Error(`Plugin source pin mismatch: ${path}`);
  }
  const source = JSON.parse(await readFile(resolve(root, 'packages/opencode-chi-mentions/package.json'), 'utf8'));
  const manifest = { name: source.name, version: source.version, private: true, type: 'module', exports: source.exports,
    dependencies: { '@opencode/plugin': source.dependencies['@opencode/plugin'] }, peerDependencies: source.peerDependencies };
  const lockBytes = await readFile(new URL('../plugin-lock.json', import.meta.url), 'utf8');
  const lock = JSON.parse(lockBytes);
  const first = lock.packages?.[''];
  if (lock.lockfileVersion !== 3 || lock.name !== manifest.name || lock.version !== manifest.version || first?.name !== manifest.name || first.version !== manifest.version
    || JSON.stringify(first.dependencies) !== JSON.stringify(manifest.dependencies)
    || JSON.stringify(first.peerDependencies) !== JSON.stringify(manifest.peerDependencies)) throw new Error('Plugin dependency lock mismatch');
  for (const [name, entry] of Object.entries(lock.packages)) {
    if (name && (!name.startsWith('node_modules/') || name.split('/').includes('..') || name.includes('\\') || entry.link || !entry.resolved?.startsWith('https://registry.npmjs.org/') || !/^sha512-[A-Za-z0-9+/]+=*$/.test(entry.integrity ?? ''))) throw new Error('Plugin dependencies must be integrity-pinned public npm tarballs');
    if (name) {
      const url = new URL(entry.resolved);
      if (url.origin !== 'https://registry.npmjs.org' || url.username || url.password || url.search || url.hash) throw new Error('Plugin dependency URL may not carry credentials or alternate destinations');
    }
  }
  const result = await build({
    absWorkingDir: root, entryPoints: Object.fromEntries(['index', 'tui', 'rpc', 'source'].map(name => [name, `packages/opencode-chi-mentions/${name}.js`])),
    outdir: 'plugin', write: false, bundle: true, splitting: true, metafile: true,
    platform: 'node', format: 'esm', target: 'node24', legalComments: 'inline', packages: 'external',
    alias: {
      '@henkaku-center/chi-native/auth': resolve(root, 'packages/chi-native/src/github-login.ts'),
      '@henkaku-center/chi-native/repository': resolve(root, 'packages/chi-native/src/repository.ts'),
      '@henkaku-center/chi-native/http': resolve(root, 'backend/scripts/http-client.ts'),
    },
  });
  for (const path of Object.keys(result.metafile.inputs)) if (!Object.hasOwn(sources.chi.files, path)) throw new Error(`Unreviewed plugin build input: ${path}`);
  for (const output of Object.values(result.metafile.outputs)) for (const item of output.imports) {
    if (item.external && !['node:child_process', 'node:util', '@opencode/plugin', '@opencode/plugin/rpc', '@opencode/plugin/tui'].includes(item.path)) throw new Error(`Unreviewed plugin external dependency: ${item.path}`);
  }
  const files = { 'package.json': JSON.stringify(manifest, null, 2) + '\n', 'package-lock.json': lockBytes };
  for (const file of result.outputFiles) {
    const name = relative(resolve(root, 'plugin'), file.path);
    if (!/^[A-Za-z0-9-]+\.js$/.test(name)) throw new Error('Unexpected plugin output');
    files[name] = file.text;
  }
  if (createHash('sha256').update(JSON.stringify(files)).digest('hex') !== sources.chi.payloadSha256) throw new Error('Plugin payload/compiler/dependency pin mismatch');
  await writeFile(new URL('../dist/plugin.js', import.meta.url), `// Generated by scripts/plugin.mjs; covered by installer package integrity/provenance.\nexport const plugin = ${JSON.stringify({ source: sources.chi, files })};\n`);
}
